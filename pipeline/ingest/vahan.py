def load_real_files() -> pd.DataFrame | None:
    """Load any CSV/XLSX files in data/raw/vahan/."""
    files = list(RAW_VAHAN_DIR.glob("*.csv")) + list(RAW_VAHAN_DIR.glob("*.xlsx"))
    if not files:
        return None

    dfs = []
    for f in files:
        try:
            if f.suffix == ".xlsx":
                df = pd.read_excel(f)
            else:
                df = pd.read_csv(f)
            df["_source_file"] = f.name
            dfs.append(df)
            logger.info("Loaded VAHAN file: %s (%d rows)", f.name, len(df))
        except Exception as e:
            logger.warning("Could not load %s: %s", f, e)

    if not dfs:
        return None

    combined = pd.concat(dfs, ignore_index=True)
    # Normalise column names
    combined.columns = [c.strip().upper().replace(" ", "_") for c in combined.columns]
    return combined


def generate_synthetic_data() -> pd.DataFrame:
    """
    Generate a plausible synthetic monthly EV registration series for Maharashtra.
    Based on publicly reported totals (all marked SYNTHETIC).

    State-level totals are approximate from press releases / media reports.
    District allocation uses population share (SYNTHETIC).
    """
    logger.warning("Using SYNTHETIC VAHAN data — see data_status='synthetic' in DB and UI badge.")

    # Approximate Maharashtra state-level monthly EV totals (all classes combined)
    # Source: analyst estimates based on media/policy reports — SYNTHETIC
    monthly_totals = {
        (2020, m): 500 + m * 30 for m in range(1, 13)
    }
    monthly_totals.update({(2021, m): 900 + m * 80 for m in range(1, 13)})
    monthly_totals.update({(2022, m): 2500 + m * 200 for m in range(1, 13)})
    monthly_totals.update({(2023, m): 6000 + m * 400 for m in range(1, 13)})
    monthly_totals.update({(2024, m): 10000 + m * 600 for m in range(1, 13)})

    vehicle_class_splits = {"2W": 0.55, "3W": 0.25, "4W": 0.18, "bus": 0.01, "other": 0.01}

    rows = []
    for (year, month), total in monthly_totals.items():
        for vc, vc_share in vehicle_class_splits.items():
            vc_total = total * vc_share
            for district, dist_share in MH_DISTRICT_SHARES.items():
                count = max(0, int(round(vc_total * dist_share + np.random.normal(0, 2))))
                rows.append({
                    "STATE": STATE,
                    "RTO_CODE": f"MH-{district[:3].upper()}",
                    "RTO_NAME": district,
                    "YEAR": year,
                    "MONTH": month,
                    "FUEL": "ELECTRIC",
                    "VEHICLE_CLASS": vc,
                    "COUNT": count,
                    "DATA_STATUS": "synthetic",
                })

    return pd.DataFrame(rows)


def map_vehicle_class(raw_class: str) -> str:
    return VEHICLE_CLASS_MAP.get(str(raw_class).upper().strip(), "other")


def load_into_db(df: pd.DataFrame, data_status: str = "observed") -> None:
    engine = create_engine(DB_URL, pool_pre_ping=True)
    inserted = 0
    with engine.begin() as conn:
        for _, row in df.iterrows():
            vc = map_vehicle_class(row.get("VEHICLE_CLASS", ""))
            conn.execute(text("""
                INSERT INTO raw.ev_registrations_vahan
                    (state, rto_code, rto_name, year, month, fuel, vehicle_class, count, source, fetched_at)
                VALUES (:state, :rto_code, :rto_name, :year, :month, :fuel, :vehicle_class, :count, :source, NOW())
            """), {
                "state": row.get("STATE", STATE),
                "rto_code": row.get("RTO_CODE", ""),
                "rto_name": row.get("RTO_NAME", ""),
                "year": int(row.get("YEAR", 0)),
                "month": int(row.get("MONTH", 0)),
                "fuel": row.get("FUEL", "ELECTRIC"),
                "vehicle_class": vc,
                "count": int(row.get("COUNT", 0)),
                "source": row.get("_source_file", data_status),
            })
            inserted += 1
    logger.info("Inserted %d rows into raw.ev_registrations_vahan (%s)", inserted, data_status)


def main():
    logger.info("=== VAHAN EV Registration Ingestion for %s ===", STATE)
    write_manual_export_guide()

    df = load_real_files()
    if df is not None:
        logger.info("Real VAHAN data found (%d rows). Loading as 'observed'.", len(df))
        load_into_db(df, "observed")
    else:
        logger.info("No real VAHAN files found in data/raw/vahan/ — generating synthetic data.")
        df_syn = generate_synthetic_data()
        cache = RAW_VAHAN_DIR / f"synthetic_vahan_{STATE_CODE}_{datetime.utcnow().strftime('%Y%m%d')}.csv"
        df_syn.to_csv(cache, index=False)
        logger.info("Saved synthetic VAHAN data to %s", cache)
        load_into_db(df_syn, "synthetic")

    logger.info("VAHAN ingestion complete.")


if __name__ == "__main__":
    main()
